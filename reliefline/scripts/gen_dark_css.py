"""Generate the dark-mode half of every app stylesheet.

The app's CSS hardcodes its colours (white cards, #1a1a1a text, pale tinted
badges ...), so instead of hand-writing a dark override for each of ~12k
lines, this script reads every rule in app/static/css/*.css and appends a
dark twin of it to the same file:

    .panel { background: white; color: #1a1a1a; }
    ->  html[data-theme="dark"] .panel { background: #1c1f2a; color: #ddd; }

Only colour-bearing property families are copied (background*, color,
border*, outline*, fill, stroke, colour custom properties). Every rule that
sets one of those properties gets a twin - even when its value doesn't
change - so the twins keep the exact cascade order/specificity relationships
of the originals (a light `.tab.active` still beats a light `.tab`, and so
do their dark twins).

Colours are remapped by role: light surfaces -> dark surfaces, dark text ->
light text, accents lightened enough to read on dark, light borders -> dark
borders. Mid/dark backgrounds (buttons, badges with white text) stay as-is.

The twins live after a marker at the bottom of each file, inside
@media screen (printing always stays light). Rerun after editing any CSS:

    python scripts/gen_dark_css.py

Hand-written dark tweaks go in dark.css, which this script never touches.
"""
import colorsys
import os
import re
import sys

CSS_DIR = os.path.join(os.path.dirname(__file__), "..", "app", "static", "css")
# Public pages (landing / login) keep their own look; dark.css is hand-written.
SKIP_FILES = {"landing.css", "login.css", "login_page.css", "dark.css"}
MARKER = "/* ===== DARK MODE - generated by scripts/gen_dark_css.py from the rules above. Do not edit below this line; rerun the script. ===== */"
DARK = 'html[data-theme="dark"]'

PROP_ROLE = [
    (re.compile(r"^background(-color|-image)?$"), "bg"),
    (re.compile(r"^background-"), "keep"),
    (re.compile(r"^(fill|stroke)$"), "svg"),
    (re.compile(r"^(color|-webkit-text-fill-color|caret-color|text-decoration-color)$"), "fg"),
    (re.compile(r"^(border|outline|column-rule)(-.*)?$"), "border"),
]


# --- colour parsing / mapping -------------------------------------------------

NAMED = {"white": (255, 255, 255), "black": (0, 0, 0)}
COLOR_RE = re.compile(
    r"#[0-9a-fA-F]{3,8}\b|rgba?\([^)]*\)|\b(?:white|black)\b(?![-\w])", re.I)


def parse_color(tok):
    t = tok.lower()
    if t in NAMED:
        return (*NAMED[t], 1.0)
    if t.startswith("#"):
        h = t[1:]
        if len(h) in (3, 4):
            h = "".join(c * 2 for c in h)
        if len(h) not in (6, 8):
            return None
        r, g, b = (int(h[i:i + 2], 16) for i in (0, 2, 4))
        a = int(h[6:8], 16) / 255 if len(h) == 8 else 1.0
        return r, g, b, a
    m = re.match(r"rgba?\(\s*([\d.]+)[\s,]+([\d.]+)[\s,]+([\d.]+)(?:[\s,/]+([\d.]+%?))?\s*\)", t)
    if not m:
        return None
    r, g, b = (float(m.group(i)) for i in (1, 2, 3))
    a = m.group(4)
    a = 1.0 if a is None else (float(a[:-1]) / 100 if a.endswith("%") else float(a))
    return r, g, b, a


def fmt(r, g, b, a):
    r, g, b = (max(0, min(255, round(v))) for v in (r, g, b))
    if a >= 0.999:
        return f"#{r:02x}{g:02x}{b:02x}"
    return f"rgba({r}, {g}, {b}, {round(a, 3)})"


def hls(rgb):
    return colorsys.rgb_to_hls(*(v / 255 for v in rgb))


def from_hls(h, l, s, a):
    r, g, b = colorsys.hls_to_rgb(h, max(0, min(1, l)), max(0, min(1, s)))
    return fmt(r * 255, g * 255, b * 255, a)


NEUTRAL_HUE = 228 / 360   # the app's blue-grey


SURFACE = (28, 31, 41)      # #1c1f29 - the dark card surface tints sit on


def map_bg(c):
    r, g, b, a = c
    h, l, s = hls((r, g, b))
    if l >= 0.8:
        if s < 0.3 or l > 0.975:          # white / grey surfaces
            return from_hls(NEUTRAL_HUE, 0.135 + (1 - l) * 0.55, 0.18, a)
        # Pale tints (badges, highlighted rows, icon boxes): a thin wash of
        # the hue over the dark surface - just enough to read as "amber" or
        # "green", never a loud coloured block.
        tr, tg, tb = (v * 255 for v in colorsys.hls_to_rgb(h, 0.55, min(s, 0.75)))
        # Near-white tints (whole highlighted rows, hover fills) get half the
        # wash of badge-strength tints - a full-width band reads much louder.
        k = 0.07 if l >= 0.96 else 0.14
        return fmt(*(SURFACE[i] * (1 - k) + (tr, tg, tb)[i] * k for i in range(3)), a)
    return fmt(r, g, b, a)                 # accents / dark fills stay


def map_fg(c):
    r, g, b, a = c
    h, l, s = hls((r, g, b))
    if s < 0.25:
        if l <= 0.55:                      # dark neutral text
            return from_hls(NEUTRAL_HUE, 0.92 - l * 0.5, min(s, 0.12), a)
        return fmt(r, g, b, a)             # mid greys read fine on dark
    if l < 0.68:                           # accent text (navy, violet, green, red...)
        return from_hls(h, max(0.68, min(0.78, l + 0.22)), s, a)
    return fmt(r, g, b, a)


def map_border(c):
    r, g, b, a = c
    h, l, s = hls((r, g, b))
    if l >= 0.75:
        if s < 0.3 or l > 0.975:
            return from_hls(NEUTRAL_HUE, 0.24 + (1 - l) * 0.3, 0.15, a)
        return from_hls(h, 0.28, s * 0.5, a)
    if l <= 0.3 and s < 0.25:              # dark neutral lines -> light lines
        return from_hls(NEUTRAL_HUE, 0.85 - l, 0.1, a)
    return fmt(r, g, b, a)


def map_svg(c):
    """SVG fill/stroke: pale shapes are surfaces (chart bands), dark ones text."""
    _, l, _ = hls(c[:3])
    return map_bg(c) if l >= 0.8 else map_fg(c)


MAPPERS = {"bg": map_bg, "fg": map_fg, "border": map_border, "svg": map_svg}


def remap(value, role):
    if role == "keep":
        return value
    fn = MAPPERS[role]

    def sub(m):
        if m.group(0).lower().startswith("url"):
            return m.group(0)
        c = parse_color(m.group(0))
        return fn(c) if c else m.group(0)

    # Leave url(...) contents (data URIs) alone.
    parts = re.split(r"(url\([^)]*\))", value)
    return "".join(p if p.startswith("url(") else COLOR_RE.sub(sub, p) for p in parts)


def role_for(prop, value):
    if prop.startswith("--"):
        if not COLOR_RE.fullmatch(value.strip().replace(" !important", "")):
            return None
        n = prop.lower()
        if any(k in n for k in ("border", "line")):
            return "border"
        if any(k in n for k in ("canvas", "surface", "bg", "tint")):
            return "bg"
        if any(k in n for k in ("text", "muted", "ink")):
            return "fg"
        return None
    for rx, role in PROP_ROLE:
        if rx.match(prop):
            return role
    return None


# --- tiny CSS parser ----------------------------------------------------------

def strip_comments(css):
    return re.sub(r"/\*.*?\*/", "", css, flags=re.S)


def find_block_end(css, i):
    """css[i] == '{' -> index of the matching '}'."""
    depth, q = 0, None
    while i < len(css):
        ch = css[i]
        if q:
            if ch == "\\":
                i += 1
            elif ch == q:
                q = None
        elif ch in "\"'":
            q = ch
        elif ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
            if depth == 0:
                return i
        i += 1
    return len(css)


def split_decls(body):
    out, cur, depth, q = [], "", 0, None
    for ch in body:
        if q:
            cur += ch
            if ch == q:
                q = None
            continue
        if ch in "\"'":
            q = ch
        elif ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        elif ch == ";" and depth == 0:
            out.append(cur)
            cur = ""
            continue
        cur += ch
    out.append(cur)
    return [d.strip() for d in out if d.strip()]


def split_selectors(prelude):
    out, cur, depth = [], "", 0
    for ch in prelude:
        if ch in "([":
            depth += 1
        elif ch in ")]":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(cur.strip())
            cur = ""
        else:
            cur += ch
    out.append(cur.strip())
    return [s for s in out if s]


def dark_selector(sel):
    if sel.startswith(":root"):
        return DARK + sel[len(":root"):]
    m = re.match(r"^html\b", sel)
    if m:
        return DARK + sel[4:]
    return f"{DARK} {sel}"


def convert(css, indent=""):
    """Return the dark twins for every rule in `css`."""
    out = []
    i = 0
    while i < len(css):
        brace = css.find("{", i)
        semi = css.find(";", i)
        if brace == -1:
            break
        if semi != -1 and semi < brace:          # @import / @charset ...
            i = semi + 1
            continue
        prelude = css[i:brace].strip()
        end = find_block_end(css, brace)
        body = css[brace + 1:end]
        i = end + 1
        if prelude.startswith("@"):
            at = prelude.lower()
            if (at.startswith("@media") or at.startswith("@supports")) and "print" not in at:
                inner = convert(body, indent + "    ")
                if inner:
                    out.append(f"{indent}{prelude} {{\n{inner}\n{indent}}}")
            continue                               # keyframes, font-face, page, print
        decls = []
        for d in split_decls(body):
            if ":" not in d:
                continue
            prop, val = d.split(":", 1)
            prop, val = prop.strip(), val.strip()
            role = role_for(prop.lower() if not prop.startswith("--") else prop, val)
            if role is None:
                continue
            decls.append(f"{prop}: {remap(val, role)};")
        if not decls:
            continue
        sels = ", ".join(dark_selector(s) for s in split_selectors(prelude))
        out.append(f"{indent}{sels} {{ {' '.join(decls)} }}")
    return "\n".join(out)


def main():
    changed = 0
    for name in sorted(os.listdir(CSS_DIR)):
        if not name.endswith(".css") or name in SKIP_FILES:
            continue
        path = os.path.join(CSS_DIR, name)
        with open(path, encoding="utf-8", newline="") as f:
            text = f.read()
        eol = "\r\n" if "\r\n" in text else "\n"   # keep the file's line endings
        light = text.split(MARKER)[0].rstrip() + eol
        twins = convert(strip_comments(light), "    ")
        new = light if not twins else light + (
            f"\n{MARKER}\n@media screen {{\n{twins}\n}}\n".replace("\n", eol))
        if new != text:
            with open(path, "w", encoding="utf-8", newline="") as f:
                f.write(new)
            changed += 1
        print(f"{name}: {twins.count(chr(10)) + 1 if twins else 0} dark rules")
    print(f"{changed} file(s) updated")


if __name__ == "__main__":
    sys.exit(main())
